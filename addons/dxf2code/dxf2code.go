// Package dxf2code generates Go source that recreates a drawing's entity
// inventory via the graphics factory API.
package dxf2code

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/edanko/dxf/addons"
	"github.com/edanko/dxf/drawing"
	"github.com/edanko/dxf/entity"
)

func init() { _ = addons.Register("dxf2code", capability{}) }

type capability struct{}

func (capability) Name() string { return "dxf2code" }
func (capability) Description() string {
	return "generate Go source recreating a drawing entity inventory"
}

// Generate emits Go source that rebuilds the entity inventory of d.
func Generate(d *drawing.Drawing) (string, error) {
	var b strings.Builder
	b.WriteString("// Code generated by dxf2code; DO NOT EDIT.\n")
	b.WriteString("package main\n\n")
	b.WriteString("import (\n\t\"github.com/edanko/dxf/drawing\"\n)\n\n")
	b.WriteString("func main() {\n")
	b.WriteString("\td, err := drawing.New()\n\tif err != nil {\n\t\tpanic(err)\n\t}\n")
	b.WriteString("\tms := d.Model()\n")
	for _, e := range d.Entities() {
		switch t := e.(type) {
		case *entity.Line:
			fmt.Fprintf(&b, "\tif _, err := ms.AddLine(%s, %s, %s, %s, %s, %s); err != nil {\n\t\tpanic(err)\n\t}\n",
				f(t.Start[0]), f(t.Start[1]), f(t.Start[2]), f(t.End[0]), f(t.End[1]), f(t.End[2]))
		case *entity.Circle:
			fmt.Fprintf(&b, "\tif _, err := ms.AddCircle(%s, %s, %s, %s); err != nil {\n\t\tpanic(err)\n\t}\n",
				f(t.Center[0]), f(t.Center[1]), f(t.Center[2]), f(t.Radius))
		case *entity.Text:
			fmt.Fprintf(&b, "\tif _, err := ms.AddText(%s, %s, %s, %s, %s); err != nil {\n\t\tpanic(err)\n\t}\n",
				f(t.Coord1[0]), f(t.Coord1[1]), f(t.Coord1[2]), f(t.Height), q(t.Value))
		default:
			fmt.Fprintf(&b, "\t// skipped %s [%s]\n", e.DXFType(), e.Handle())
		}
	}
	b.WriteString("\t_ = d\n}\n")
	return b.String(), nil
}

func f(v float64) string { return strconv.FormatFloat(v, 'g', -1, 64) }

func q(s string) string { return strconv.Quote(s) }
